'''
Q1. What is OpenAI?
A.
OpenAI is an AI research and deployment company that develops
large-scale foundation models (like GPT) and provides them
through APIs and products such as ChatGPT.
'''

# Example:
# Developers call OpenAI’s API to generate text,
# answer questions, or build AI copilots.


'''
Q2. What are foundation models built by OpenAI?
A.
Foundation models are large-scale pretrained models trained
on massive datasets that can be adapted to many tasks
like text generation, coding, reasoning, and image creation.
'''

# Example:
# GPT → text generation
# DALL·E → image generation
# Whisper → speech-to-text


'''
Q3. What is the difference between GPT and ChatGPT?
A.
GPT is the underlying language model technology.
ChatGPT is a product built on top of GPT models,
with additional interface, safety, and system features.
'''

# Example:
# GPT = engine
# ChatGPT = application using that engine


'''
Q4. What does OpenAI provide to developers?
A.
OpenAI provides APIs for text generation, embeddings,
tool calling, image generation, speech processing,
and multimodal capabilities.
'''

# Example:
# Use OpenAI API to build:
# - Chatbots
# - RAG systems
# - AI assistants
# - Code copilots


'''
Q5. How is OpenAI different from Hugging Face?
A.
OpenAI builds and hosts proprietary models accessed via API.
Hugging Face is an ecosystem platform hosting many
open-source models and ML tooling.
'''

# Example:
# OpenAI → API access to GPT models
# Hugging Face → Download and run LLaMA locally


'''
Q6. How is OpenAI different from LangChain?
A.
OpenAI is a model provider.
LangChain is a framework used to build structured systems
around LLMs, including chaining, retrieval, and agents.
'''

# Example:
# OpenAI → Provides GPT API
# LangChain → Orchestrates GPT + tools + memory
