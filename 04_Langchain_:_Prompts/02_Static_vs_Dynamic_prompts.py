'''
🔹 Static vs Dynamic Prompts — Clear Comparison

Static Prompt:
- Fixed instruction
- No variables
- Same every time

Example:
"Summarize this article."

Best for:
✔ Quick tests
✔ Simple tasks

Limitation:
❌ Not reusable
❌ Not scalable

--------------------------------------------------

Dynamic Prompt:
- Uses variables
- Generated at runtime
- Reusable template

Example:
"Summarize {article} in {tone} tone."

Best for:
✔ Production systems
✔ Multi-user apps
✔ RAG pipelines
✔ Scalable design

--------------------------------------------------

Core Difference:

Static  → Hardcoded string  
Dynamic → Parameterized template  

--------------------------------------------------

One-Line Summary:
Static prompts are fixed; dynamic prompts are flexible,
reusable templates designed for scalable applications.
'''